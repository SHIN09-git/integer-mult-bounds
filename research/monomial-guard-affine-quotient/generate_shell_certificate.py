"""Generate untrusted witnesses for the kernel-checked five-row census."""
import argparse
from pathlib import Path

from verify import add, paid_moves, signature


def encode(rows, mode):
    return tuple(9 * u + 3 * w + b for u, w, b in signature(rows, mode))


def unpack(code):
    return tuple((x // 9, x // 3 % 3, x % 3) for x in code)


def lean_list(values):
    return "[" + ",".join(map(str, values)) + "]"


def table(name, type_name, entries):
    return f"def {name} : List {type_name} := [\n  " + ",\n  ".join(entries) + "]\n"


def generate():
    start = ((1, 1, 1),) * 4 + ((1, 2, 0),)
    rows = [encode(start, "rows")]
    positions = {rows[0]: 0}
    edges = []
    parent = [0]
    moves = paid_moves(5)
    first = 0
    for _ in range(3):
        end = len(rows)
        for i in range(first, end):
            state = unpack(rows[i])
            targets = []
            for move in moves:
                child = encode(add(state, move), "rows")
                if child not in positions:
                    positions[child] = len(rows)
                    rows.append(child)
                    parent.append(i)
                targets.append(positions[child])
            edges.append(targets)
        first = end
    affine = [encode(unpack(row), "affine") for row in rows]
    blocks = [
        "import AffineGuard.FiveEncoding\n",
        "/-! Generated by generate_shell_certificate.py. FiveCounts checks these witnesses in Lean. -/\n",
        "namespace AffineGuard.Census.Table\n",
        table("rows", "Code", map(lean_list, rows)),
        table("edges", "(List ℕ)", map(lean_list, edges)),
        table("affine", "Code", map(lean_list, affine)),
        "def parent : List ℕ := " + lean_list(parent) + "\n",
        "end AffineGuard.Census.Table\n",
    ]
    return "\n".join(blocks)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare against the checked-in table")
    args = parser.parse_args()
    target = Path(__file__).parent / "AffineGuard" / "FiveTable.lean"
    generated = generate().encode("utf-8")
    if args.check:
        if target.read_bytes() != generated:
            raise SystemExit("The generated table differs from the checked-in file.")
        print("The generated table matches the checked-in file.")
    else:
        target.write_bytes(generated)
